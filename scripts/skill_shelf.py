"""Generate, or check, the generated parts of the plugin's skills.

Generated by geostack (``scripts/skill_tree.py --shelf-check``), which holds
the one copy every library with a shelf uses; do not edit it here.

The plugin (``plugins/<name>/``) ships the library's guidance as a shelf:
``tree/shelf.toml`` lists its listed skills, its units and one entry per job,
each entry with the public names it covers. An entry is a file in its skill's
``shelf/`` folder; a unit has a contract card in ``tree/cards/``.

The shelf file also says where the public names are read from, one line per
public module, as a path from the repository's root::

    [modules]
    gaussx = "src/gaussx/__init__.py"

With one module an entry lists bare names (``"solve"``); with several, as in
a workspace or a library of public submodules, it lists them with their
module (``"functax.geometry.Affine"``).

This script writes the two parts of each ``SKILL.md`` that follow from the
shelf file, so nobody edits them by hand:

- the table of the skill's entries, between ``shelf:begin`` and ``shelf:end``;
- the cards of the units below the skill, between ``shelf:below:begin`` and
  ``shelf:below:end``.

``--check`` fails when either is stale, and on the shelf's gates:

- SH-1: every public name of every module belongs to exactly one entry, and
  the entry's file names it;
- SH-2: every ``module.X`` a unit card writes is a public name;
- SH-3: the authored part of a ``SKILL.md`` has at most 150 lines, an entry
  at most 120, a card at most 15.

The "Builds on" block at the end of each ``SKILL.md`` (between
``skill-tree:begin`` and ``skill-tree:end``) is not written here: it follows
from the dependency graph of the whole stack, and geostack's
``scripts/skill_tree.py`` generates it.

Usage::

    python scripts/skill_shelf.py            # rewrite the parts
    python scripts/skill_shelf.py --check    # fail if stale

The public names are read from the source of each module, so the script
imports nothing.
"""

from __future__ import annotations

import argparse
import ast
import re
import sys
import tomllib
from dataclasses import dataclass
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]

TABLE = ("<!-- shelf:begin -->", "<!-- shelf:end -->")
BELOW = ("<!-- shelf:below:begin -->", "<!-- shelf:below:end -->")
TREE_MARK = "<!-- skill-tree:begin"

SKILL_MAX_LINES = 150
ENTRY_MAX_LINES = 120
CARD_MAX_LINES = 15

ROLE_MARKS = {
    "structure": "⓪ structure",
    "primitive": "① primitive",
    "strategy": "② strategy",
    "setup": "setup",
    "model": "③ model",
    "algorithm": "④ algorithm",
    "step": "⑤ step",
    "recipe": "⑥ recipe",
}


@dataclass(frozen=True)
class Unit:
    """A group of entries the same dependents use; it has one card."""

    key: str
    title: str
    rungs: str
    skill: str


@dataclass(frozen=True)
class Entry:
    """One entry: a file in a listed skill's ``shelf/``, and the names it covers."""

    file: str
    title: str
    role: str
    unit: str
    skill: str
    covers: str
    names: tuple[str, ...]


@dataclass(frozen=True)
class Shelf:
    """The shelf file: modules, skills (with the units below each), units, entries."""

    modules: dict[str, str]
    skills: dict[str, tuple[str, ...]]
    units: dict[str, Unit]
    entries: tuple[Entry, ...]


def plugin_dir() -> Path:
    """The repository's plugin: the one folder of ``plugins/`` with a shelf file.

    Raises:
        LookupError: If no plugin, or more than one, has a ``tree/shelf.toml``.
    """
    found = sorted(p.parents[1] for p in ROOT.glob("plugins/*/tree/shelf.toml"))
    if len(found) != 1:
        raise LookupError(f"expected one plugins/*/tree/shelf.toml, found {len(found)}")
    return found[0]


def load(path: Path | None = None) -> Shelf:
    """Read the shelf file."""
    path = path if path is not None else plugin_dir() / "tree" / "shelf.toml"
    raw = tomllib.loads(path.read_text(encoding="utf-8"))
    return Shelf(
        modules=dict(raw["modules"]),
        skills={
            k: tuple(v.get("builds_on_units", ())) for k, v in raw["skills"].items()
        },
        units={
            k: Unit(k, u["title"], u["rungs"], u["skill"])
            for k, u in raw["units"].items()
        },
        entries=tuple(
            Entry(
                e["file"],
                e["title"],
                e["role"],
                e["unit"],
                e["skill"],
                e["covers"],
                tuple(e["names"]),
            )
            for e in raw["entries"]
        ),
    )


def _all(init: Path) -> set[str]:
    """Every name a module's source puts in ``__all__``, extras included.

    Names that need an extra are often appended to ``__all__`` inside a
    ``try``; reading the source finds them whether or not it is installed.
    """
    names: set[str] = set()
    for node in ast.walk(ast.parse(init.read_text(encoding="utf-8"))):
        if isinstance(node, ast.Assign):
            targets = node.targets
        elif isinstance(node, ast.AugAssign):
            targets = [node.target]
        else:
            continue
        if any(isinstance(t, ast.Name) and t.id == "__all__" for t in targets):
            names |= {
                c.value
                for c in ast.walk(node.value)
                if isinstance(c, ast.Constant) and isinstance(c.value, str)
            }
    return names


def module_names(shelf: Shelf) -> dict[str, set[str]]:
    """The public names of each module, without the modules the shelf lists.

    A public submodule that the shelf lists as a module of its own
    (``functax.geometry``) is covered by its names, not as a name of its parent.
    """
    return {
        module: {n for n in _all(ROOT / init) if f"{module}.{n}" not in shelf.modules}
        for module, init in shelf.modules.items()
    }


def public_names(shelf: Shelf | None = None) -> set[str]:
    """Every public name the entries must cover, as an entry writes it.

    Bare with one module, ``module.name`` with several.
    """
    shelf = shelf if shelf is not None else load()
    names = module_names(shelf)
    if len(names) == 1:
        return set().union(*names.values())
    return {f"{module}.{n}" for module, found in names.items() for n in found}


def skill_file(skill: str) -> Path:
    return plugin_dir() / "skills" / skill / "SKILL.md"


def entry_file(entry: Entry) -> Path:
    return plugin_dir() / "skills" / entry.skill / "shelf" / f"{entry.file}.md"


def card_file(unit: str) -> Path:
    return plugin_dir() / "tree" / "cards" / f"{unit}.md"


def cited(shelf: Shelf, card: str) -> list[tuple[str, str]]:
    """Each ``module.X`` a card writes right after a backtick, as (module, X).

    The module is the longest one the shelf lists that the dotted name starts
    with; a name that is itself a listed module cites nothing.
    """
    out = []
    for dotted in re.findall(r"`([A-Za-z_][A-Za-z0-9_.]*[A-Za-z0-9_])", card):
        if dotted in shelf.modules:
            continue
        for module in sorted(shelf.modules, key=len, reverse=True):
            if dotted.startswith(module + "."):
                name = dotted[len(module) + 1 :].split(".")[0]
                if f"{module}.{name}" not in shelf.modules:
                    out.append((module, name))
                break
    return out


def table(shelf: Shelf, skill: str) -> str:
    """The table of a listed skill's entries."""
    rows = ["| Role | Entry | Covers | Names |", "|---|---|---|---|"]
    for e in shelf.entries:
        if e.skill == skill:
            role = ROLE_MARKS.get(e.role, e.role)
            link = f"[{e.title}](shelf/{e.file}.md)"
            rows.append(f"| {role} | {link} | {e.covers} | {len(e.names)} |")
    return "\n".join(rows)


def below(shelf: Shelf, skill: str) -> str:
    """The cards of the units of the library that a listed skill builds on."""
    parts = [
        "## The units below this skill",
        "",
        "A card is enough to call a unit.",
        "Load its skill only when the card's last line applies.",
    ]
    for key in shelf.skills[skill]:
        unit = shelf.units[key]
        parts += [
            "",
            f"### {unit.title} · {unit.rungs} · skill"
            f" `{plugin_dir().name}:{unit.skill}`",
            "",
            card_file(key).read_text(encoding="utf-8").strip(),
        ]
    return "\n".join(parts)


def _replace(text: str, markers: tuple[str, str], body: str, where: str) -> str:
    begin, end = markers
    if begin not in text or end not in text.split(begin, 1)[1]:
        raise ValueError(f"{where}: needs {begin} and {end}")
    head, rest = text.split(begin, 1)
    middle = f"\n{body}\n" if body else "\n"
    return f"{head}{begin}{middle}{end}{rest.split(end, 1)[1]}"


def render(shelf: Shelf, skill: str, text: str) -> str:
    """``text`` (a listed ``SKILL.md``) with its generated parts rewritten."""
    text = _replace(text, TABLE, table(shelf, skill), skill)
    if shelf.skills[skill]:
        text = _replace(text, BELOW, below(shelf, skill), skill)
    elif BELOW[0] in text:
        # the skill no longer builds on a unit: its old cards go
        text = _replace(text, BELOW, "", skill)
    return text


def authored_lines(text: str) -> int:
    """Lines of a ``SKILL.md`` an author wrote: all but the generated parts."""
    text = text.split(TREE_MARK, 1)[0]
    for begin, end in (TABLE, BELOW):
        if begin in text and end in text:
            text = text.split(begin, 1)[0] + text.split(end, 1)[1]
    return len(text.rstrip("\n").splitlines())


def violations(shelf: Shelf, names: set[str]) -> list[str]:
    """Every stale part and every gate that fails; empty when all hold."""
    out: list[str] = []
    public = module_names(shelf)
    for skill in shelf.skills:
        text = skill_file(skill).read_text(encoding="utf-8")
        if render(shelf, skill, text) != text:
            out.append(f"stale: {skill}/SKILL.md (run scripts/skill_shelf.py)")
        if authored_lines(text) > SKILL_MAX_LINES:
            out.append(f"SH-3 {skill}: {authored_lines(text)} authored lines")
    seen: dict[str, str] = {}
    for e in shelf.entries:
        unit = shelf.units.get(e.unit)
        if unit is None or e.skill not in shelf.skills or unit.skill != e.skill:
            out.append(f"SH-1 {e.file}: its unit and its skill disagree")
        if e.role not in ROLE_MARKS:
            out.append(f"SH-1 {e.file}: unknown role {e.role!r}")
        for name in e.names:
            if name in seen:
                out.append(f"SH-1 {name}: in {seen[name]} and in {e.file}")
            seen[name] = e.file
        path = entry_file(e)
        if not path.is_file():
            out.append(f"SH-1 {e.file}: no entry file")
            continue
        text = path.read_text(encoding="utf-8")
        if len(text.splitlines()) > ENTRY_MAX_LINES:
            out.append(f"SH-3 {e.file}: over {ENTRY_MAX_LINES} lines")
        words = set(re.findall(r"[A-Za-z_][A-Za-z0-9_]*", text))
        out += [
            f"SH-1 {e.file}: does not name {n}"
            for n in sorted(e.names)
            if n.rsplit(".", 1)[-1] not in words
        ]
    out += [f"SH-1 {n}: public, in no entry" for n in sorted(names - set(seen))]
    out += [f"SH-1 {n}: in {seen[n]}, not public" for n in sorted(set(seen) - names)]
    for key in shelf.units:
        path = card_file(key)
        if not path.is_file():
            out.append(f"SH-2 {key}: no card")
            continue
        card = path.read_text(encoding="utf-8").strip()
        if len(card.splitlines()) > CARD_MAX_LINES:
            out.append(f"SH-3 {key}: card over {CARD_MAX_LINES} lines")
        out += [
            f"SH-2 {key}: no public name {module}.{name}"
            for module, name in sorted(set(cited(shelf, card)))
            if name not in public[module]
        ]
    return out


def examples(root: Path | None = None) -> list[tuple[Path, str]]:
    """Every fenced ``python`` block of the plugin's Markdown, with its file."""
    out = []
    for path in sorted((root or plugin_dir()).rglob("*.md")):
        for block in re.findall(r"```python\n(.*?)```", path.read_text("utf-8"), re.S):
            out.append((path, block))
    return out


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if stale")
    args = parser.parse_args(argv)
    shelf = load()
    if not args.check:
        for skill in shelf.skills:
            path = skill_file(skill)
            text = path.read_text(encoding="utf-8")
            new = render(shelf, skill, text)
            if new != text:
                path.write_text(new, encoding="utf-8")
                print(f"wrote {path.relative_to(ROOT)}")
    found = violations(shelf, public_names(shelf))
    for message in found:
        print(message)
    return 1 if found else 0


if __name__ == "__main__":
    sys.exit(main())
